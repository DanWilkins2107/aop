describe("asking", () => {
  it("ask moves the node and posts the question, and the answer starts the stage again", TIMEOUT, async () => {
    w = await world();
    const node = await w.create(
      directives(
        `ifnot Use the blue one :: aop ["ask","Which colour?"]`,
        `ifnot Use the blue one :: exit 0`,
        `record ${w.file("second.json")}`,
        'aop ["next","fixed"]',
      ),
    );
    await w.atStage(node.id, "ask_human_question");
    const [first] = await w.runsEnded(node.id);
    expect(first).toMatchObject({ end_reason: "reported", left_via: "ask" });
    expect(claimOf(node.id)).toBeNull();
    const messages = (await w.call<MessageRow[]>("GET", `/nodes/${node.id}/messages`)).body;
    expect(messages.map((m) => [m.author, m.body])).toEqual([["agent", "Which colour?"]]);

    await settle();
    expect(w.runs(node.id)).toHaveLength(1);

    await w.call("POST", `/nodes/${node.id}/answer`, { answer: "Use the blue one" });
    await w.atStage(node.id, "done");
    expect(w.runs(node.id)).toHaveLength(2);
    expect(recorded("second.json").stdin).toContain("Use the blue one");
  });

  it("retrying a failed node starts its stage again", TIMEOUT, async () => {
    w = await world();
    const node = await w.create(directives("exit 1"));
    await w.atStage(node.id, "failed");
    await w.runsEnded(node.id);
    await w.call("PATCH", `/nodes/${node.id}`, { body: directives('aop ["next","fixed"]') });
    await w.call("POST", `/nodes/${node.id}/retry`);
    await w.atStage(node.id, "done");
    expect(w.runs(node.id)).toHaveLength(2);
  });
});
